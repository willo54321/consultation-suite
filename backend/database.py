class Query(Base):
    """Stakeholder queries/feedback submissions"""
    __tablename__ = "queries"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    project_id = Column(UUID(as_uuid=True), ForeignKey("projects.id", ondelete="CASCADE"), nullable=False)
    widget_id = Column(UUID(as_uuid=True), ForeignKey("widgets.id", ondelete="SET NULL"))

    # Submitter info
    submitter_name = Column(String(255))
    submitter_email = Column(String(255))
    submitter_phone = Column(String(50))
    submitter_address = Column(Text)

    # Query content
    subject = Column(String(500))
    content = Column(Text, nullable=False)
    submission_data = Column(JSONB, default={})  # Additional form fields
    attachments = Column(ARRAY(String), default=[])

    # Status and workflow
    status = Column(String(50), default="new")  # new, in_progress, awaiting_approval, approved, sent, closed
    priority = Column(String(20), default="medium")  # low, medium, high, urgent
    category_id = Column(UUID(as_uuid=True), ForeignKey("query_categories.id", ondelete="SET NULL"))
    assigned_to = Column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL"))
    tags = Column(ARRAY(String), default=[])

    # Metadata
    source = Column(String(50), default="form")  # form, email, phone, in_person
    ip_hash = Column(String(64))
    user_agent = Column(Text)

    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    # Relationships
    project = relationship("Project", back_populates="queries")
    widget = relationship("Widget", back_populates="form_submissions")
    category = relationship("QueryCategory", back_populates="queries")
    assignee = relationship("User", foreign_keys=[assigned_to], back_populates="assigned_queries")
    responses = relationship("QueryResponse", back_populates="query", cascade="all, delete-orphan")
    notes = relationship("QueryNote", back_populates="query", cascade="all, delete-orphan")


