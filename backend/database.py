from sqlalchemy.dialects.postgresql import UUID, JSONB
from sqlalchemy.orm import declarative_base, relationship, sessionmaker, Session
from pgvector.sqlalchemy import Vector
from config import get_settings

settings = get_settings()

engine = create_engine(settings.database_url)
SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)
Base = declarative_base()


def get_db():
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()


class Project(Base):
    __tablename__ = "projects"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    name = Column(String(255), nullable=False)
    client = Column(String(255))
    site_address = Column(Text)
    status = Column(String(50), default="draft")  # draft, live, closed
    persona_prompt = Column(Text)
    welcome_message = Column(Text, default="Hello! I'm here to help answer your questions about this development proposal. What would you like to know?")
    disclaimer = Column(Text, default="This response is generated by an AI assistant based on published consultation materials. For detailed queries, please contact the consultation team.")
    fallback_message = Column(Text, default="I don't have enough information to answer that question accurately. Please contact our team directly for assistance.")
    contact_email = Column(String(255))
    blocked_topics = Column(ARRAY(String), default=[])
    widget_config = Column(JSONB, default={})
    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    # Relationships
    documents = relationship("Document", back_populates="project", cascade="all, delete-orphan")
    chunks = relationship("Chunk", back_populates="project", cascade="all, delete-orphan")
    manual_qas = relationship("ManualQA", back_populates="project", cascade="all, delete-orphan")
    conversations = relationship("Conversation", back_populates="project", cascade="all, delete-orphan")


class Document(Base):
    __tablename__ = "documents"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    project_id = Column(UUID(as_uuid=True), ForeignKey("projects.id", ondelete="CASCADE"), nullable=False)
    filename = Column(String(255), nullable=False)
    original_filename = Column(String(255))
    file_type = Column(String(50))  # pdf, docx, txt
    content_type = Column(String(50), default="public")  # public, internal
    upload_date = Column(DateTime, default=datetime.utcnow)
    processed = Column(Boolean, default=False)
    processing_error = Column(Text)
    page_count = Column(Integer)
    tags = Column(ARRAY(String), default=[])

    # Relationships
    project = relationship("Project", back_populates="documents")
    chunks = relationship("Chunk", back_populates="document", cascade="all, delete-orphan")


class Chunk(Base):
    __tablename__ = "chunks"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    document_id = Column(UUID(as_uuid=True), ForeignKey("documents.id", ondelete="CASCADE"))
    project_id = Column(UUID(as_uuid=True), ForeignKey("projects.id", ondelete="CASCADE"), nullable=False)
    content = Column(Text, nullable=False)
    page_number = Column(Integer)
    chunk_index = Column(Integer)
    token_count = Column(Integer)
    embedding = Column(Vector(1536))
    chunk_metadata = Column(JSONB, default={})
    source_type = Column(String(50), default="document")  # document, url, manual
    source_url = Column(Text)

    # Relationships
    document = relationship("Document", back_populates="chunks")
    project = relationship("Project", back_populates="chunks")


# Create index for vector similarity search
Index(
    "chunks_embedding_idx",
    Chunk.embedding,
    postgresql_using="ivfflat",
    postgresql_with={"lists": 100},
    postgresql_ops={"embedding": "vector_cosine_ops"},
)


